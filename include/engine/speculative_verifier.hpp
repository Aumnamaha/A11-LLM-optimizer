// K=8 draft tokens per speculation step
constexpr uint32_t SPEC_K = 8;

namespace A11 {
namespace Engine {

/// Represents a node in the draft token tree.
struct TreeNode {
    int32_t  token_id      = -1;       // Drafted token id
    float    log_prob      = 0.0f;     // Draft model log-prob
    uint32_t parent_idx    = UINT32_MAX; // Parent node index in tree
    uint32_t depth         = 0;        // Depth in draft tree (0=root)
    std::vector<uint32_t> children;    // Child node indices
};

/// Diagnostic counters for speculative decoding telemetry.
struct SpecDiagnosticCounters {
    uint64_t steps_accepted   = 0;     // Total tokens accepted via speculation
    uint64_t steps_rejected   = 0;     // Steps where rejection sampling failed
    uint64_t fallback_count   = 0;     // Fallbacks to single-token autoregressive gen
    uint64_t total_draft_tokens = 0;   // Draft tokens generated across all steps
    uint64_t total_steps      = 0;     // Total speculation steps attempted

    void log_fallback(uint32_t draft_len, uint32_t accepted) {
        ++fallback_count;
        std::cerr << "[SpeculativeVerifier DIAGNOSTIC] Fallback to autoregressive: "
                  << "draft=" << draft_len
                  << ", accepted=" << accepted
                  << ", step #" << total_steps << std::endl;
    }

    void reset() {
        steps_accepted = 0;
        steps_rejected = 0;
        fallback_count = 0;
        total_draft_tokens = 0;
        total_steps = 0;
    }
};

/// Core tree speculative verification engine.
/// Validates K=8 draft tokens generated by a smaller draft model or n-gram
/// proposal engine against the target model's probability distribution in a
/// single parallel forward pass, with rejection sampling acceptance criteria.
class SpeculativeTreeVerifier {
public:
    struct Config {
        uint32_t  max_draft_depth = SPEC_K;   // Max draft tree depth (K=8)
        uint32_t  vocab_size      = 32000;     // Vocabulary size for masking
        float     acceptance_threshold = 1.0f; // Accept if r < min(1, p_target/p_draft)
        bool      log_diagnostics = true;       // Enable diagnostic logging
    };

    explicit SpeculativeTreeVerifier(const Config& cfg);
    ~SpeculativeTreeVerifier();

    SpeculativeTreeVerifier(const SpeculativeTreeVerifier&) = delete;
    SpeculativeTreeVerifier& operator=(const SpeculativeTreeVerifier&) = delete;

    /// Build a balanced K-ary draft tree from proposed token sequences.
    /// Each node at depth d has up to K children at depth d+1.
    /// @param root_token The root (first) drafted token id
    /// @return TreeNode representing the tree root, with children filled in
    TreeNode build_draft_tree(int32_t root_token);

    /// Construct the verification mask for parallel tree evaluation.
    /// For each draft token, the mask indicates which tokens from the
    /// target vocabulary need probability evaluation. Returns a flat
    /// [num_nodes x vocab_size] mask where mask[i * vocab + j] = 1 if
    /// position (i,j) needs attention computation.
    std::vector<float> construct_tree_mask(const std::vector<TreeNode>& tree);

    /// Verify draft tokens against target model probabilities.
    /// Implements rejection sampling: for each draft token in order,
    /// accept with probability min(1, p_target / p_draft).
    /// @param draft_tokens Vector of drafted token ids (depth-first order)
    /// @param draft_log_probs Log-probs from the draft model
    /// @param target_log_probs Log-probs from the target model for same tokens
    /// @return Pair of (accepted_length, last_accepted_index_in_draft)
    std::pair<uint32_t, uint32_t> verify_draft_tokens(
        const std::vector<int32_t>& draft_tokens,
        const std::vector<float>& draft_log_probs,
        const std::vector<float>& target_log_probs);

    /// Full speculation step: build tree, construct mask, verify.
    /// This is the main entry point for one speculation iteration.
    /// @param context_tokens Existing context tokens (prefix)
    /// @param root_draft_token First token from draft model
    std::pair<std::vector<int32_t>, bool> speculate_step(
        const std::vector<int32_t>& context_tokens,
        int32_t root_draft_token);

    /// Get diagnostic counters for telemetry/benchmarking.
    const SpecDiagnosticCounters& diagnostics() const { return diags_; }

    /// Reset all diagnostic counters.
    void reset_diagnostics();

private:
    Config config_;
    SpecDiagnosticCounters diags_;

    /// Sample a uniform random float in [0, 1) for rejection sampling.
    static float rand_uniform();

    /// Validate that target probabilities are within valid range.
    bool validate_target_probs(const std::vector<float>& probs) const;

    /// Build depth-first traversal order of the draft tree.
    void build_dfs_order(uint32_t node_idx, std::vector<uint32_t>& dfs_order);
};

} // namespace Engine
} // namespace A11

#endif // A11_SPECULATIVE_VERIFIER_HPP
